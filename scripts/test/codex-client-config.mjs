#!/usr/bin/env node
// E6 客户端加载验证（离线）：把网关生成的 Codex 目录 + D1-A 配置写成真实 CODEX_HOME/config.toml，
// 再由 Codex 自己加载（不带 -c 覆盖）。不启动网络请求、不读真实 ~/.codex、不需要登录。
import { spawnSync } from 'node:child_process'
import { mkdtemp, readFile, writeFile, rm, copyFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { existsSync } from 'node:fs'
import { buildCatalog } from '../../src/codex/catalog.js'

const CODEX = process.env.CODEX_BIN || 'codex'
const basePath = process.env.MG_E3_CATALOG_BASE || '/tmp/mg-e0/catalog-default.json'
const checks = []
const check = (n, ok, d) => { checks.push(ok); console.log((ok ? 'PASS' : 'FAIL') + '  ' + n + (d ? ' :: ' + d : '')) }
if (!existsSync(basePath)) { console.error('缺少官方目录基线: ' + basePath); process.exit(2) }

const home = await mkdtemp(join(tmpdir(), 'mg-e6-client-'))
try {
  const base = JSON.parse(await readFile(basePath, 'utf8'))
  const cfg = { providers: { opencodego: { baseUrl: 'https://opencode.ai/inference/go', api: 'openai' } }, models: { 'deepseek-v4.1-flash': { provider: 'opencodego', api: 'openai', maxContext: 128000 } } }
  const { catalog } = buildCatalog({ base, config: cfg })
  const catalogPath = join(home, 'catalog.json')
  await writeFile(catalogPath, JSON.stringify(catalog))
  const toml = [
    '# generated by scripts/test/codex-client-config.mjs',
    'model = "gpt-6-astra"',
    'model_provider = "openai"',
    'openai_base_url = "http://127.0.0.1:8787"',
    'model_catalog_json = "' + catalogPath + '"',
    'approval_policy = "never"',
    '',
    '[features]',
    'multi_agent = true',
    '',
    '[mcp_servers.demo]',
    'command = "true"',
    'args = []',

    ''
  ].join(String.fromCharCode(10))
  await writeFile(join(home, 'config.toml'), toml)

  const run = (args) => spawnSync(CODEX, args, { env: Object.assign({}, process.env, { CODEX_HOME: home }), encoding: 'utf8', timeout: 60000 })
  const models = run(['debug', 'models'])
  check('Codex 能加载 config.toml（debug models exit 0）', models.status === 0, 'code=' + models.status + ' err=' + String(models.stderr || '').slice(-300))
  let parsed = null
  try { parsed = JSON.parse(models.stdout) } catch {}
  check('目录可解析为 {models:[…]}', !!parsed && Array.isArray(parsed.models), parsed ? 'models=' + parsed.models.length : 'parse failed')
  const slugs = parsed && Array.isArray(parsed.models) ? parsed.models.map((m) => m.slug) : []
  check('目录包含官方 slug（gpt-6-astra）', slugs.includes('gpt-6-astra'), 'count=' + slugs.length)
  check('目录包含第三方聚合 slug', slugs.includes('mg-opencodego-deepseek-v4-1-flash'), slugs.slice(-2).join(','))
  check('没有 [model_providers.openai] 冲突（否则启动失败）', !/reserved built-in provider IDs/.test(String(models.stderr || '') + String(models.stdout || '')))
  const features = run(['features', 'list'])
  check('features list 同样能加载配置', features.status === 0 && /multi_agent/.test(String(features.stdout || '')))
} finally {
  await rm(home, { recursive: true, force: true })
}
const failed = checks.filter((x) => !x).length
console.log(String.fromCharCode(10) + (checks.length - failed) + '/' + checks.length + ' client-config checks passed')
process.exitCode = failed ? 1 : 0
